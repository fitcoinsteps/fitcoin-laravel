$i = 1
foreach ($table in $tables) {
    $num = $i.ToString("D6")  # e.g. 000001, 000002, ...
    $migrationName = "create_${table}_table"

    Write-Host "Creating migration for $table ($num)..."

    # Generate the migration file
    php artisan make:migration $migrationName

    # Wait a moment to ensure file is written
    Start-Sleep -Milliseconds 500

    # Find the latest migration file (the one we just created)
    $latest = Get-ChildItem -Path database/migrations -Filter "*.php" |
              Sort-Object LastWriteTime -Descending |
              Select-Object -First 1

    if ($latest) {
        $newName = "2025_01_01_${num}_${migrationName}.php"
        Rename-Item -Path $latest.FullName -NewName $newName
        Write-Host "  -> Renamed to $newName"
    } else {
        Write-Host "ERROR: No migration file found after artisan command!"
        exit 1
    }
    $i++
}

Write-Host "All 304 migration files created and renamed successfully!"